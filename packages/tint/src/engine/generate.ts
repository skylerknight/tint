// ─────────────────────────────────────────────────────────────
// Constants
// ─────────────────────────────────────────────────────────────

const WHITE: GeneratedColor = {
  hex: "#ffffff",
  rgb: { r: 255, g: 255, b: 255 },
  oklch: { l: 1, c: 0, h: 0 },
};

const BLACK: GeneratedColor = {
  hex: "#000000",
  rgb: { r: 0, g: 0, b: 0 },
  oklch: { l: 0, c: 0, h: 0 },
};

const BASELINE: Record<Mode, GeneratedColor> = { light: WHITE, dark: BLACK };

/** Chroma ceiling for ls (surface) tokens, by step count. */
export function maxChromaForLs(ls: number): number {
  if (ls <= 0) return 0.02;
  if (ls <= 3) return 0.05;
  if (ls <= 7) return 0.08;
  return 0.12;
}

