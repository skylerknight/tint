// Public API
// ─────────────────────────────────────────────────────────────

/**
 * Generate palettes from a tint config (or an array of configs for multi-theme setups).
 *
 * The input is validated (`assertConfig`), resolved (`resolveConfig`), and then every
 * palette is generated by walking the token dependency graph in topological order.
 * Output is deterministic: identical configs produce byte-identical results.
 */
export function generate(configs: readonly unknown[]): GenerationResult[];
export function generate(config: Config | unknown): GenerationResult;
export function generate(input: unknown): GenerationResult | GenerationResult[] {
  if (Array.isArray(input)) {
    return (input as readonly unknown[]).map((config) => generateOne(config));
  }
  return generateOne(input);
}

// ─────────────────────────────────────────────────────────────
// Pipeline
// ─────────────────────────────────────────────────────────────

function generateOne(input: unknown): GenerationResult {
  const config = assertConfig(input);
  const resolved = resolveConfig(config);
  const diagnostics: Diagnostic[] = [];

  for (const color of resolved.colors) {
    const prefix = color.name.toLowerCase();
    if (Object.hasOwn(TAILWIND_UTILITY_PREFIXES, prefix)) {
      diagnostics.push({
        severity: "warning",
        code: "palette-name-conflict",
        path: color.name,
        message:
          `Palette name "${color.name}" matches the Tailwind utility prefix "${prefix}". ` +
          `Shortcut classes like "${prefix}-<variant>" will refer to this palette when no tint-* class is applied.`,
        hint: `Rename the color (for example "${color.name}Color") to avoid ambiguous class names.`,
      });
    }
  }

  const palettes = resolved.colors.map((color) =>
    generatePalette(color.name, color.input, resolved, diagnostics),
  );

  const result: GenerationResult = {
    name: resolved.name,
    mode: resolved.mode,
    selector: resolved.selector,
    palettes,
    diagnostics,
    warnings: diagnostics.map((d) => d.message),
  };
  if (resolved.prefersColorScheme !== undefined) {
    result.prefersColorScheme = resolved.prefersColorScheme;
  }
  if (resolved.prefersContrast !== undefined) {
    result.prefersContrast = resolved.prefersContrast;
  }
  return result;
}

function generatePalette(
  name: string,
  input: string,
  resolved: ResolvedConfig,
  diagnostics: Diagnostic[],
): GeneratedPalette {
  const seed = parseSeed(name, input, diagnostics);
  const overrides = resolved.overrides[name] ?? {};
  const generated: Record<string, Record<string, GeneratedVariant>> = {};

  // Pre-create groups/variant slots in config order so the output object keeps the
  // author's ordering regardless of the topological walk below.
  for (const [groupName, group] of Object.entries(resolved.groups)) {
    const slot: Record<string, GeneratedVariant> = {};
    for (const variantName of Object.keys(group.variants)) {
      // Placeholder keys preserve insertion order; filled in during the walk.
      slot[variantName] = undefined as unknown as GeneratedVariant;
    }
    generated[groupName] = slot;
  }

  for (const { group, variant } of resolved.order) {
    const spec = resolved.groups[group]?.variants[variant];
    if (!spec) continue;
    const override = overrides[`${group}.${variant}`];
    const token = generateVariant(
      name,
      spec,
      override,
      seed,
      resolved,
      generated,
      diagnostics,
    );
    generated[group]![variant] = token;
  }

  return { name, seed: seed.color, tokens: generated };
}

// ─────────────────────────────────────────────────────────────
// Seeds
// ─────────────────────────────────────────────────────────────

interface Seed {
  color: GeneratedColor;
  oklch: OKLCH;
}

function parseSeed(name: string, input: string, diagnostics: Diagnostic[]): Seed {
  const rgb = parseColor(input);
  const oklch = rgbToOKLCH(rgb);
  const trimmed = input.trim().toLowerCase();

  if (trimmed.startsWith("oklch(")) {
    const requested = parseOKLCH(trimmed);
    if (!isOKLCHInGamut(requested)) {
      diagnostics.push({
        severity: "warning",
        code: "seed-out-of-gamut",
        path: name,
        message:
          `Seed color "${input}" for "${name}" is outside the sRGB gamut and was mapped to ` +
          `${rgbToHex(rgb)} (oklch ${oklch.l.toFixed(3)} ${oklch.c.toFixed(3)} ${oklch.h.toFixed(1)}).`,
        hint: "Lower the chroma of the seed to keep it inside sRGB.",
        data: { requested, mapped: oklch },
      });
    }
  }

  return { color: { hex: rgbToHex(rgb), rgb, oklch }, oklch };
}

// ─────────────────────────────────────────────────────────────
// Variants
// ─────────────────────────────────────────────────────────────

interface EffectiveVariant {
  value: number;
  scale: number;
  chroma: number;
  decorative: boolean;
  invert: boolean;
}

function applyOverride(
  spec: ResolvedVariant,
  override: ResolvedOverride | undefined,
): EffectiveVariant {
  return {
    value: override?.value ?? spec.value,
    scale: override?.scale ?? spec.scale,
    chroma: override?.chroma ?? spec.chroma,
    decorative: override?.decorative ?? spec.decorative,
    invert: override?.invert ?? spec.invert,
  };
}

function toGenerated(oklch: OKLCH): GeneratedColor {
  const mapped = toGamut(oklch);
  const rgb = oklchToRGBGamut(mapped);
  return { hex: rgbToHex(rgb), rgb, oklch: mapped };
}

function withMeta<T extends GeneratedVariant>(
  token: T,
  spec: ResolvedVariant,
  decorative: boolean,
): T {
  if (spec.reference) token.reference = true;
  if (spec.on) token.on = `${spec.on.group}.${spec.on.variant}`;
  if (decorative) token.decorative = true;
  return token;
}

function generateVariant(
  palette: string,
  spec: ResolvedVariant,
  override: ResolvedOverride | undefined,
  seed: Seed,
  resolved: ResolvedConfig,
  generated: Record<string, Record<string, GeneratedVariant>>,
  diagnostics: Diagnostic[],
): GeneratedVariant {
  const effective = applyOverride(spec, override);
  const mode = resolved.mode;
  const path = `${palette}.${spec.group}.${spec.name}`;

  // Working seed: the palette seed with the chroma multiplier applied once.
  const working = toGamut({
    l: seed.oklch.l,
    c: seed.oklch.c * effective.chroma,
    h: seed.oklch.h,
  });

  // Reference color: the resolved `on` target (already generated), else the mode baseline.
  let reference: GeneratedColor = BASELINE[mode];
  if (spec.on) {
    const target = generated[spec.on.group]?.[spec.on.variant];
    if (!target) {
      throw new Error(
        `Internal error: "${spec.group}.${spec.name}" depends on "${spec.on.group}.${spec.on.variant}" which has not been generated yet.`,
      );
    }
    reference = target;
  }

  // Zero steps / zero contrast against a reference means "exactly the reference".
  if (spec.on && effective.value === 0) {
    const copy = {
      hex: reference.hex,
      rgb: { ...reference.rgb },
      oklch: { ...reference.oklch },
    };
    return spec.kind === "ls"
      ? withMeta({ ...copy, kind: "ls", ls: 0 }, spec, effective.decorative)
      : withMeta({ ...copy, kind: "lc", lc: 0, target: 0 }, spec, effective.decorative);
  }

  if (spec.kind === "ls") {
    return generateLs(spec, effective, working, reference, resolved);
  }
  return generateLc(spec, effective, working, reference, mode, path, diagnostics);
}

function generateLs(
  spec: ResolvedVariant,
  effective: EffectiveVariant,
  working: OKLCH,
  reference: GeneratedColor,
  resolved: ResolvedConfig,
): GeneratedVariant {
  const mode = resolved.mode;

  if (effective.value === PURE) {
    const pure = BASELINE[mode];
    return withMeta(
      {
        hex: pure.hex,
        rgb: { ...pure.rgb },
        oklch: { ...pure.oklch },
        kind: "ls",
        ls: PURE,
      },
      spec,
      effective.decorative,
    );
  }

  // Foundation ls variants step from the foundation surface (pure ∓ offset), not from pure.
  let anchorL = reference.oklch.l;
  if (!spec.on) {
    anchorL = mode === "light" ? 1 - resolved.offset : resolved.offset;
  }

  const steps = effective.value * effective.scale;
  const l = clamp01(mode === "light" ? anchorL - steps : anchorL + steps);
  const c = Math.min(working.c, maxChromaForLs(effective.value));
  const color = toGenerated({ l, c, h: working.h });

  return withMeta(
    { ...color, kind: "ls", ls: effective.value },
    spec,
    effective.decorative,
  );
}

function generateLc(
  spec: ResolvedVariant,
  effective: EffectiveVariant,
  working: OKLCH,
  reference: GeneratedColor,
  mode: Mode,
  path: string,
  diagnostics: Diagnostic[],
): GeneratedVariant {
  let polarity: Polarity;
  if (spec.on) {
    polarity = preferredPolarity(reference.rgb);
    if (effective.invert) polarity = polarity === "lighter" ? "darker" : "lighter";
  } else {
    polarity = mode === "light" ? "darker" : "lighter";
  }

  if (effective.value === PURE) {
    // Foundation `pure` is the mode baseline; with a reference it is whichever extreme
    // sits on the chosen side of that reference.
    const pure = spec.on ? (polarity === "lighter" ? WHITE : BLACK) : BASELINE[mode];
    const lc = calcAPCAabs(pure.rgb, reference.rgb);
    return withMeta(
      {
        hex: pure.hex,
        rgb: { ...pure.rgb },
        oklch: { ...pure.oklch },
        kind: "lc",
        lc,
        target: PURE,
      },
      spec,
      effective.decorative,
    );
  }

  const target = effective.value;

  if (spec.on && !effective.decorative) {
    if (target > 0 && target < APCA_MINIMUM_LC) {
      diagnostics.push({
        severity: "warning",
        code: "contrast-below-minimum",
        path,
        message:
          `${path} requests Lc ${target}, below the APCA minimum of Lc ${APCA_MINIMUM_LC}. ` +
          `Colors this close to their reference are not distinguishable as foreground elements.`,
        hint: "Use an ls variant for subtle surfaces, or mark the variant $decorative.",
        data: { target },
      });
    }
    const minimum = spec.role ? ROLE_MIN_LC[spec.role] : undefined;
    if (minimum !== undefined && target < minimum) {
      diagnostics.push({
        severity: "warning",
        code: "role-contrast-low",
        path,
        message: `${path} requests Lc ${target}, below the recommended minimum of Lc ${minimum} for the "${spec.role}" role.`,
        hint: `Raise lc to at least ${minimum}, change $role, or mark the variant $decorative.`,
        data: { target, minimum, role: spec.role },
      });
    }
  }

  let solved = solveContrast(working, reference.rgb, target, { polarity });

  if (!solved.reached && spec.on && !effective.invert) {
    const opposite: Polarity = polarity === "lighter" ? "darker" : "lighter";
    const alternative = solveContrast(working, reference.rgb, target, {
      polarity: opposite,
    });
    if (alternative.lc > solved.lc) solved = alternative;
  }

  if (!solved.reached) {
    reportUnreachable(
      spec,
      target,
      working,
      reference,
      path,
      effective.invert ? polarity : null,
      diagnostics,
    );
  }

  const color = toGenerated(solved.color);
  return withMeta(
    { ...color, kind: "lc", lc: solved.lc, target },
    spec,
    effective.decorative,
  );
}

function reportUnreachable(
  spec: ResolvedVariant,
  target: number,
  working: OKLCH,
  reference: GeneratedColor,
  path: string,
  lockedPolarity: Polarity | null,
  diagnostics: Diagnostic[],
): void {
  // `$invert` locks the polarity, so only that side counts as "achievable".
  const lighter = maxContrast(working, reference.rgb, "lighter");
  const darker = maxContrast(working, reference.rgb, "darker");
  let best = lighter.lc >= darker.lc ? lighter : darker;
  let bestPolarity: Polarity = lighter.lc >= darker.lc ? "lighter" : "darker";
  if (lockedPolarity) {
    best = lockedPolarity === "lighter" ? lighter : darker;
    bestPolarity = lockedPolarity;
  }
  const refLabel = spec.on ? `${spec.on.group}.${spec.on.variant}` : "the mode baseline";
  const refL = reference.oklch.l;
  const midtone =
    spec.on !== null && !lockedPolarity && refL > 0.35 && refL < 0.75 && best.lc < 70;

  let hint: string;
  if (lockedPolarity) {
    hint =
      `$invert forces a ${bestPolarity} foreground, which reaches at most Lc ${best.lc.toFixed(0)} against "${refLabel}". ` +
      `Lower the target, drop $invert, or move "${refLabel}" ${bestPolarity === "lighter" ? "darker" : "lighter"}.`;
  } else if (midtone) {
    hint =
      `"${refLabel}" is a mid-tone (L=${refL.toFixed(2)}), so neither light nor dark foregrounds reach high contrast. ` +
      `Make "${refLabel}" darker (so light text works) or lighter (so dark text works), or accept Lc ${best.lc.toFixed(0)} for large/bold text.`;
  } else {
    hint = `The highest contrast available against ${refLabel} (${reference.hex}) is Lc ${best.lc.toFixed(0)} with a ${bestPolarity} foreground.`;
  }

  diagnostics.push({
    severity: "warning",
    code: "contrast-unreachable",
    path,
    message: `${path} requests Lc ${target} but only Lc ${best.lc.toFixed(1)} is achievable against ${refLabel} (${reference.hex}).`,
    hint,
    data: { target, achievable: best.lc, reference: reference.hex, referenceL: refL },
  });

  if (midtone) {
    diagnostics.push({
      severity: "warning",
      code: "reference-midtone",
      path,
      message: `${refLabel} (${reference.hex}, L=${refL.toFixed(2)}) is a mid-tone reference; the maximum reachable contrast against it is Lc ${best.lc.toFixed(0)}.`,
      hint: `Move "${refLabel}" away from mid lightness so dependent tokens can reach their targets.`,
      data: { reference: reference.hex, referenceL: refL, achievable: best.lc },
    });
  }
}

function clamp01(value: number): number {
  return Math.min(1, Math.max(0, value));
}

